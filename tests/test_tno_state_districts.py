def test_append_preserves_existing_bytes_and_is_idempotent():
    original = b'{\r\n  "version": 1,\r\n  "tags": {\r\n    "AAA": {"old": true}\r\n  },\r\n  "tail": [ 1 ]\r\n}\r\n'
    additions = {'BBB': {'name': '新组'}}
    changed = builder.append_tags_bytes(original, 'tags', additions)
    assert b'    "AAA": {"old": true},\r\n' in changed
    assert changed.endswith(b'  },\r\n  "tail": [ 1 ]\r\n}\r\n')
    assert json.loads(changed)['tags'] == {'AAA': {'old': True}, **additions}
    assert builder.append_tags_bytes(changed, 'tags', additions) == changed


@pytest.mark.skipif(not (builder.registration.TNO_ROOT / 'localisation/english/state_names_l_english.yml').exists()
                    or not (builder.BASE_LOCALISATION / 'simp_chinese/state_names_l_simp_chinese.yml').exists(),
                    reason='本机游戏本地化文件不存在')
def test_generated_names_resolve_from_game_localization():
    english = builder.localization(builder.registration.TNO_ROOT / 'localisation/english/state_names_l_english.yml')
    base = builder.exact_name_translations(builder.localization(builder.BASE_LOCALISATION / 'english/state_names_l_english.yml'),
                                           builder.localization(builder.BASE_LOCALISATION / 'simp_chinese/state_names_l_simp_chinese.yml'))
    for tag, record in published().items():
        if tag in builder.MANUAL_TAGS:
            continue
        en_counts, zh_counts = Counter(), Counter()
        for district_id, group in record['districts'].items():
            sid = int(district_id.removeprefix('state_'))
            name_en = english[f'STATE_{sid}'] if sid else 'Antarctic Territories'
            name_zh = (base[name_en] if name_en in base else builder.TRANSLATIONS[name_en]) if sid else '南极属地'
            en_counts[name_en] += 1
            zh_counts[name_zh] += 1
            assert group['name_en'] == name_en + (f' {en_counts[name_en]}' if en_counts[name_en] > 1 else '')
            assert group['name_zh'] == name_zh + (f' {zh_counts[name_zh]}' if zh_counts[name_zh] > 1 else '')


