def build_overlay(districts, owners, countries, existing_overlay, releasables=()):
    retired = {entry["tag"] for entry in releasables}
    entries = [entry for entry in existing_overlay["entries"] if entry["tag"] not in retired]
    existing_ids = {entry["id"] for entry in entries}
    family_countries = {**countries, **{entry["tag"]: entry for entry in entries}}
    for tag, en, zh, parent, kind, district in PILOTS + DISTRICTS:
        entry_id = f"tno_{tag.lower()}"
        if entry_id in existing_ids:
            continue
        feature_ids = (D(parent, district, districts, owners) if isinstance(district, str)
                       else sorted(fid for fid in district if owners.get(fid) == parent))
        if not feature_ids:
            raise ValueError(f"entry {entry_id}: empty district selection")
        color = family_palette(
            family_countries[parent]["color_hex"], 1,
            existing_colors=[country["color_hex"] for country in family_countries.values()
                             if country.get("parent_owner_tag") == parent],
            **WIDE_FAMILIES.get(parent, {}),
        )[0]
        entry = {"id": entry_id, "scenarios": ["tno_1962"], "tag": tag,
         "name_en": en, "name_zh": zh, "parent_owner_tag": parent,
         "subject_kind": kind, "cores": "keep", "only_from_owners": [parent],
         "select": {"feature_ids": feature_ids}, "color_hex": color}
        entries.append(entry)
        family_countries[tag] = entry
    for spec in EXPLICIT:
        entry_id = spec.get("id", f"tno_{spec['tag'].lower()}")
        if entry_id in existing_ids:
            continue
        parent = spec.get("parent_owner_tag", "")
        color = spec.get("color_hex")
        if parent:
            color = family_palette(
                family_countries[parent]["color_hex"], 1,
                existing_colors=[country["color_hex"] for country in family_countries.values()
                                 if country.get("parent_owner_tag") == parent],
                **WIDE_FAMILIES.get(parent, {}),
            )[0]
        elif not color:
            color = countries[spec["tag"]]["color_hex"]
        entry = {"id": entry_id, "scenarios": ["tno_1962"], **spec, "color_hex": color}
        entries.append(entry)
        family_countries[spec["tag"]] = entry
    for entry in releasables:
        entry_id = f"tno_reclaim_{entry['tag'].lower()}"
        if entry_id not in existing_ids:
            entries.append({"id": entry_id, "scenarios": ["tno_1962"],
                            "tag": entry["parent_owner_tag"], "cores": "parent_if_single_child",
                            "only_from_owners": [entry["tag"]],
                            "select": {"feature_ids": entry["preset_source"]["feature_ids"]}})
    return {**existing_overlay, "entries": entries}


